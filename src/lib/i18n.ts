let currentLocale: Locale = "bg";
let initialized = false;
const listeners = new Set<() => void>();

function emit() {
  listeners.forEach((listener) => listener());
}

function subscribe(listener: () => void) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

function getSnapshot() {
  return currentLocale;
}

function getServerSnapshot(): Locale {
  return "bg";
}

export function initializeLocale() {
  if (initialized || typeof window === "undefined") return;
  initialized = true;
  const stored = preferences.getLocale();
  if (stored !== currentLocale) {
    currentLocale = stored;
    emit();
  }
  document.documentElement.lang = currentLocale;
}

export function setAppLocale(locale: Locale) {
  currentLocale = locale;
  preferences.setLocale(locale);
  if (typeof document !== "undefined") document.documentElement.lang = locale;
  emit();
}

export function translate(key: string, locale: Locale = currentLocale, values?: TranslationValues) {
  const template = MESSAGES[locale]?.[key] ?? MESSAGES.en[key] ?? key;
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (_, token: string) =>
    String(values[token] ?? `{${token}}`),
  );
}

export function translateRuntimeText(text: string, locale: Locale = currentLocale) {
  if (locale === "en") return text;
  const exact = RUNTIME_BG[text];
  if (exact) return exact;

  const diagnostics = text.match(/^(\d+) geometry diagnostics?$/);
  if (diagnostics) return `${diagnostics[1]} геометрични предупреждения`;
  const matching = text.match(/^(\d[\d,.]*) matching structures$/);
  if (matching) return `${matching[1]} намерени конструкции`;
  const templates = text.match(/^(\d[\d,.]*) templates$/);
  if (templates) return `${templates[1]} шаблона`;
  return text;
}

export function useI18n() {
  const locale = useSyncExternalStore(subscribe, getSnapshot, getServerSnapshot);
  useEffect(() => initializeLocale(), []);

  return {
    locale,
    t: (key: string, values?: TranslationValues) => translate(key, locale, values),
    tr: (text: string) => translateRuntimeText(text, locale),
    setLocale: setAppLocale,
    formatNumber: (value: number) =>
      new Intl.NumberFormat(locale === "bg" ? "bg-BG" : "en-GB").format(value),
    formatDate: (value: string | number | Date) =>
      new Intl.DateTimeFormat(locale === "bg" ? "bg-BG" : "en-GB", {
        dateStyle: "medium",
        timeStyle: "short",
      }).format(new Date(value)),
  };
}
